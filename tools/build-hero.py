"""Builds the start page's background photos.

1. Put the original photo in home/hero/originals/ (the bigger the better: 2400 px wide or more).
2. Add a line for it to home/hero/slides.json: the file name, the place, where it is,
   which map view it belongs to (history, wine, nature, villages or table), the part
   of the photo to keep in view when it is cropped ("50% 50%" is the centre), and a credit.
3. Run:  python3 tools/build-hero.py

It writes web-ready copies at three widths to home/hero/ and the list the page reads,
home/hero/slides.js. Photos narrower than a screen are enlarged carefully, and the
script warns you, because they will look soft.
"""
import json, os, sys
from PIL import Image, ImageFilter, ImageOps

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
HERO = os.path.join(ROOT, "home", "hero")
WIDTHS = [960, 1600, 2400]          # phone, laptop, large or high-resolution screen
SHARP_ENOUGH = 2400

slides = json.load(open(os.path.join(HERO, "slides.json"), encoding="utf-8"))
for f in os.listdir(HERO):
    if f.endswith((".webp", ".jpg")) and os.path.isfile(os.path.join(HERO, f)):
        os.remove(os.path.join(HERO, f))
out, warnings = [], []
for s in slides:
    src = os.path.join(HERO, "originals", s["file"])
    im = ImageOps.exif_transpose(Image.open(src)).convert("RGB")
    w0, h0 = im.size
    stem = os.path.splitext(s["file"])[0]
    if w0 < SHARP_ENOUGH:
        warnings.append(f"{s['file']} is {w0} px wide. It will look soft on large screens; a {SHARP_ENOUGH} px or wider original would be sharp.")
        # sizes up to the original, plus the next size up; always at least a laptop-width copy,
    # enlarged here with care because that looks better than letting the browser stretch it
    widths = [w for w in WIDTHS if w <= w0]
    bigger = [w for w in WIDTHS if w > w0]
    if bigger: widths.append(bigger[0])
    if max(widths) < 1600: widths.append(1600)
    srcset = []
    for w in sorted(set(widths)):
        h = round(h0 * w / w0)
        r = im.resize((w, h), Image.LANCZOS)
        if w > w0:   # enlarged: restore a little edge contrast without halos
            r = r.filter(ImageFilter.UnsharpMask(radius=1.6, percent=55, threshold=2))
        name = f"{stem}-{w}.webp"
        r.save(os.path.join(HERO, name), "WEBP", quality=82, method=6)
        srcset.append(f"hero/{name} {w}w")
        if w == sorted(set(widths))[min(1, len(widths) - 1)]:
            r.save(os.path.join(HERO, f"{stem}.jpg"), "JPEG", quality=84, optimize=True, progressive=True)
    out.append({"src": f"hero/{stem}.jpg", "srcset": ", ".join(srcset), "place": s["place"], "where": s.get("where", ""),
                "map": s.get("map", "history"), "focus": s.get("focus", "50% 50%"), "credit": s.get("credit", "")})
    print(f"{s['file']}: {w0}x{h0} -> {', '.join(str(w) for w in sorted(set(widths)))} px")
with open(os.path.join(HERO, "slides.js"), "w", encoding="utf-8") as f:
    f.write("// Generated by tools/build-hero.py from home/hero/slides.json. Do not edit by hand.\nwindow.KYPROS_SLIDES = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n")
for w in warnings: print("Warning:", w)
